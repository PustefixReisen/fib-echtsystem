import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {risSessionSnapshot} from '../../packages/fachservices/src/u4-ris-session-snapshot.js';
import {risStructureCandidates} from '../../packages/fachservices/src/u4-ris-structure-candidates.js';
import {NEWS_ROOT,NEWS_ARCHIVE,scanNews,newsDetail,newsLinks} from '../../supabase/functions/_shared/u4-news.ts';
const url='https://buergerinfo-feldkirchen.digitalfabrix.de/si0057.asp?__ksinr=1032';
const html=readFileSync('tests/u4/fixtures/ris-1032-top-2-3.html','utf8');
const snapshot=risSessionSnapshot(html,url,'2026-10-31T06:00:00Z');
assert.equal(snapshot.session.committee,'Gemeinderat');
assert.equal(snapshot.session.reference,'GR/440/2026');
assert.equal(snapshot.session.date,'2026-10-29');
assert.deepEqual(snapshot.agenda.map(x=>x.topNumber),['2','3']);
assert.ok(snapshot.agenda[0].documentUrls[0].includes('id=75714'));
assert.ok(snapshot.agenda[1].documentUrls[0].includes('id=75790'));
assert.ok(snapshot.agenda.every(x=>x.decision.status==='not_verified'&&x.editorial.meldung==='not_created'));
assert.throws(()=>risStructureCandidates(html,'https://attacker.test/si0057.asp?__ksinr=1032'));
assert.throws(()=>risStructureCandidates(html,url.replace('1032','')));
const row=(n:string)=>`<tr><td>${n}</td><td><a href="vo0050.asp?__kvonr=8640">Vorlage</a></td></tr>`;
assert.equal(risStructureCandidates(row('2')+row('3'),url).length,2,'same proposal can appear at multiple TOPs');
assert.equal(risStructureCandidates(row('2')+row('2'),url).length,1,'duplicate rows deduplicated');
assert.equal(risSessionSnapshot(row('?'),url,'2026-10-31').agenda[0].issues[0],'missing_top_number');
assert.equal(risSessionSnapshot(row('2'),url,'2026-10-31').session.committee,null);
const realDetail=newsDetail(readFileSync('tests/u4/fixtures/gemeinde-detail.html','utf8'),NEWS_ROOT+'/parkraumkonzept-der-gemeinde-feldkirchen');
assert.equal(realDetail.title,'Neues Parkraumkonzept in Feldkirchen');
assert.equal(realDetail.publishedDate,'2026-09-10');
assert.equal(newsLinks(readFileSync('tests/u4/fixtures/gemeinde-current.html','utf8'),NEWS_ROOT).articles.length,15);
assert.equal(newsLinks(readFileSync('tests/u4/fixtures/gemeinde-archive.html','utf8'),NEWS_ARCHIVE).articles.length,23);
const a=NEWS_ROOT+'/article',b=NEWS_ARCHIVE+'/older',p=NEWS_ROOT+'?page=2';
const detail=(title:string,body='Nachricht mit belegtem Inhalt')=>`<html><main><nav>Navigation</nav><h1>${title}</h1><p>${body}</p></main></html>`;
const pages=new Map([[NEWS_ROOT,`<a href="${a}">A</a><a href="${p}">2</a>`],[NEWS_ARCHIVE,`<a href="${b}">B</a>`],[p,`<a href="${a}#x">A</a><a href="${NEWS_ROOT}">1</a>`],[a,detail('A')],[b,detail('B')]]);
async function main(){
 const fetcher=async(u:string)=>{if(!pages.has(u))throw Error('HTTP 503');return pages.get(u)!;};
 const result=await scanNews(fetcher);assert.equal(result.pages.length,3);assert.equal(result.articles.length,2);
 assert.equal(newsDetail(detail('A').replace('Navigation','Neue Navigation'),a).body,newsDetail(detail('A'),a).body);
 assert.equal(newsDetail(detail('A'),a).publishedDate,null);
 await assert.rejects(()=>scanNews(fetcher,2),/page_limit/);
 await assert.rejects(()=>scanNews(fetcher,20,1),/article_limit/);
 pages.set(p,'<html>not available</html>');await assert.rejects(()=>scanNews(fetcher),/empty_news_listing/);
 pages.delete(p);await assert.rejects(()=>scanNews(fetcher),/HTTP 503/);
 assert.throws(()=>newsLinks('<a rel="next" href="https://evil.test/page">Next</a>',NEWS_ROOT),/unsafe_news_next/);
 assert.throws(()=>newsDetail('<html><main><h1>A</h1><h1>B</h1></main></html>',a),/ambiguous_news_title/);
 assert.throws(()=>newsDetail(detail('A').replace('<html>','<html><link rel="canonical" href="https://evil.test/x">'),a),/invalid_news_canonical/);
 console.log('Real RIS excerpt and news archive/pagination/error contracts passed');
}
main().catch(e=>{console.error(e);process.exitCode=1});
